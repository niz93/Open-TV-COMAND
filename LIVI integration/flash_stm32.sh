#!/bin/bash

# --- PATH AND ENVIRONMENT SETTINGS ---
PORT="/dev/ttyACM0"
FIRMWARE_BIN="/home/pi/Open TV COMAND.bin" # Pure binary file generated by STM32CubeIDE
SERVICE_NAME="LiviToSerial.service"
DFU_VID_PID="0483:df11" # Standard STM32 bootloader USB VID:PID

# Function to verify if the device is currently in DFU mode (Fixed with sudo)
is_dfu_mode_active() {
    sudo dfu-util -l 2>/dev/null | grep -q "$DFU_VID_PID"
    return $?
}


echo "1. Stopping background service $SERVICE_NAME..."
sudo systemctl stop "$SERVICE_NAME"

echo "2. Validating input firmware file..."
if [ ! -f "$FIRMWARE_BIN" ]; then
    echo "❌ Error: Binary file $FIRMWARE_BIN not found!"
    sudo systemctl start "$SERVICE_NAME"
    exit 1
fi

echo "3. Analyzing current device mode..."
if is_dfu_mode_active; then
    echo "ℹ️ Device ALREADY detected in DFU mode. Skipping CDC trigger phase."
else
    echo "ℹ️ Device is in normal emulator mode. Initializing CDC boot trigger..."
    
    if [ ! -c "$PORT" ]; then
        echo "❌ Error: Port $PORT is unavailable! Check the USB connection."
        sudo systemctl start "$SERVICE_NAME"
        exit 1
    fi

    # Configure the TTY interface into raw binary mode with no echo and no buffering
    stty -F $PORT raw -echo

    # Establish a bidirectional file descriptor for port interaction
    exec 3<>$PORT
    echo -n "DFU_BOOT" >&3
    
    # Wait for the DFU_BOOT_OK acknowledgment frame from STM32 within a 3-second timeout window
    read -t 3 -r response <&3
    exec 3>&-

  if [[ "$response" == *"DFU_BOOT_OK"* ]]; then
        echo "✅ Acknowledgment received: DFU_BOOT_OK. Waiting for USB enumeration change..."
        
        # Polling loop checking for the DFU device attachment status (5-second max timeout)
        TIMEOUT=5
        while [ $TIMEOUT -gt 0 ]; do
            sleep 1
            if is_dfu_mode_active; then
                break
            fi
            ((TIMEOUT--))
        done

        if ! is_dfu_mode_active; then
            echo "❌ Error: Board acknowledged but USB DFU device ($DFU_VID_PID) failed to mount in Linux!"
            echo "Restoring background service..."
            sudo systemctl start "$SERVICE_NAME"
            exit 1
        fi    else
        echo "❌ Error: Board rejected transition or failed to reply with DFU_BOOT_OK (Reply: '$response')."
        echo "Restoring background service..."
        sudo systemctl start "$SERVICE_NAME"
        exit 1
    fi
fi

echo "4. Executing flashing sequence via dfu-util..."
# The :leave execution flag commands the STM32 kernel to exit DFU and hot-reset immediately after write
if sudo dfu-util -a 0 -s 0x08000000:leave -D "$FIRMWARE_BIN"; then
    echo "✅ Firmware image written successfully into the microcontroller internal Flash memory!"
    
    echo "5. Waiting for emulator system restart and port appearance at $PORT..."
    TIMEOUT=10
    while [ ! -c "$PORT" ] && [ $TIMEOUT -gt 0 ]; do
        sleep 1
        ((TIMEOUT--))
    done

    if [ -c "$PORT" ]; then
        echo "✅ Port $PORT is active again."
        echo "6. Launching background metadata synchronization service ($SERVICE_NAME)..."
        echo "--------------------------------------------------------"
        sudo systemctl start "$SERVICE_NAME"
        
        if systemctl is-active --quiet "$SERVICE_NAME"; then
            echo "✅ Service successfully deployed and processing CAN bus frames."
        else
            echo "❌ Error: Service registered but failed to execute. Check: journalctl -u $SERVICE_NAME"
        fi
    else
        echo "❌ Error: STM32 failed to return to Virtual COM Port mode after the flashing cycle."
        exit 1
    fi
else
    echo "❌ Error: Critical failure detected during dfu-util operations."
    echo "Attempting recovery execution for the service..."
    sudo systemctl start "$SERVICE_NAME"
    exit 1
fi
